#!/usr/bin/env bash
# Regenerate the Homebrew formula from a release's SHA256SUMS.txt.
#
#   scripts/update-formula.sh <version> <sums-file> [output]
#
# <version> is X.Y.Z (a leading "v" is accepted), <sums-file> the release's
# SHA256SUMS.txt, [output] defaults to Formula/rmx.rb in this repository.
# Fails, leaving the output untouched, if the version is malformed or any of
# the four macOS/Linux archives is missing from the sums file.
set -euo pipefail

REPO_URL="https://github.com/ismoilovdevml/rmx"

die() {
    echo "update-formula: $*" >&2
    exit 1
}

[ $# -ge 2 ] && [ $# -le 3 ] || die "usage: $0 <version> <sums-file> [output]"

version="${1#v}"
sums="$2"
out="${3:-$(cd "$(dirname "$0")/.." && pwd)/Formula/rmx.rb}"

[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "bad version '$1' (want X.Y.Z)"
[ -r "$sums" ] || die "cannot read $sums"

# sha256 of one archive, from `<hex>  <name>` (or `<hex> *<name>`) lines.
sha_of() {
    local asset="$1" hash
    hash=$(awk -v a="$asset" '{ n = $2; sub(/^\*/, "", n) } NF == 2 && n == a { print tolower($1) }' "$sums")
    [ -n "$hash" ] || die "$asset is not listed in $sums"
    [ "$(printf '%s\n' "$hash" | wc -l | tr -d ' ')" -eq 1 ] || die "$asset is listed more than once in $sums"
    [[ "$hash" =~ ^[0-9a-f]{64}$ ]] || die "malformed sha256 for $asset: $hash"
    printf '%s' "$hash"
}

# Look every hash up first: a failure inside the heredoc's command
# substitutions would not stop the script.
mac_arm=$(sha_of rmx-aarch64-apple-darwin.tar.gz)
mac_intel=$(sha_of rmx-x86_64-apple-darwin.tar.gz)
linux_arm=$(sha_of rmx-aarch64-unknown-linux-musl.tar.gz)
linux_intel=$(sha_of rmx-x86_64-unknown-linux-musl.tar.gz)

url() {
    printf '%s/releases/download/v%s/rmx-%s.tar.gz' "$REPO_URL" "$version" "$1"
}

tmp=$(mktemp "${out}.XXXXXX")
trap 'rm -f "$tmp"' EXIT

cat >"$tmp" <<EOF
# Generated by scripts/update-formula.sh from the release's SHA256SUMS.txt.
# Do not edit by hand: the release workflow rewrites it for every tag.
class Rmx < Formula
  desc "Fast alternative to rm command written in Rust"
  homepage "$REPO_URL"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$(url aarch64-apple-darwin)"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$(url x86_64-apple-darwin)"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$(url aarch64-unknown-linux-musl)"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$(url x86_64-unknown-linux-musl)"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "rmx"
  end

  test do
    assert_match "rmx v#{version}", shell_output("#{bin}/rmx --version")
  end
end
EOF

chmod 644 "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "update-formula: wrote $out for v$version"
