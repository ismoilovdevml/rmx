#!/usr/bin/env bash
# Generate the AUR packages for a release:
#   packaging/aur/rmx/           builds from the tagged source with cargo
#   packaging/aur/rmx-fast-bin/  installs the static musl release binaries
#
# Usage: scripts/update-aur.sh <version> <SHA256SUMS.txt> [out_dir]
#   version  e.g. 0.9.0 (no leading v)
# Run from the repository root at the release tag (LICENSE is hashed). Needs
# network access: the source tarball GitHub generates for the tag is hashed.
#
# AUR rules: a package that installs prebuilt binaries must carry the -bin
# suffix, so the plain name builds from source. `rmx-bin` belongs to an
# unrelated project that also installs /usr/bin/rmx, so both of ours conflict
# with it.
set -euo pipefail

REPO_URL="https://github.com/ismoilovdevml/rmx"
DESC="A faster rm written in Rust: parallel unlink, rm-compatible flags, never follows symlinks"
MAINTAINER="# Maintainer: Otabek Ismoilov <ismoilovdev at gmail dot com>"

version="${1:?version required, e.g. 0.9.0}"
sums="${2:?path to SHA256SUMS.txt required}"
out="${3:-packaging/aur}"

if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "invalid version: $version" >&2
    exit 1
fi

sha256() {
    if command -v sha256sum >/dev/null; then
        sha256sum "$1" | cut -d' ' -f1
    else
        shasum -a 256 "$1" | cut -d' ' -f1
    fi
}

sum_for() {
    local asset="$1" line
    line=$(grep -E "^[0-9a-f]{64}  ${asset}\$" "$sums" || true)
    if [ -z "$line" ]; then
        echo "no checksum for $asset in $sums" >&2
        exit 1
    fi
    printf '%s' "${line%% *}"
}

lic=$(sha256 LICENSE)
x86=$(sum_for rmx-x86_64-unknown-linux-musl.tar.gz)
arm=$(sum_for rmx-aarch64-unknown-linux-musl.tar.gz)

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL --proto '=https' --tlsv1.2 --retry 3 \
    -o "$tmp/src.tar.gz" "$REPO_URL/archive/refs/tags/v$version.tar.gz"
src=$(sha256 "$tmp/src.tar.gz")

# ---------------------------------------------------------------- rmx (source)
mkdir -p "$out/rmx"
cat > "$out/rmx/PKGBUILD" <<EOF
$MAINTAINER
# Generated by scripts/update-aur.sh; edit the script, not this file.
pkgname=rmx
pkgver=$version
pkgrel=1
pkgdesc="$DESC"
arch=('x86_64' 'aarch64')
url="$REPO_URL"
license=('MIT')
depends=('glibc' 'libgcc')
makedepends=('cargo')
conflicts=('rmx-bin' 'rmx-fast-bin')
# Cargo already strips the release binary (Cargo.toml: strip = true).
options=('!debug')
source=("\$pkgname-\$pkgver.tar.gz::\$url/archive/refs/tags/v\$pkgver.tar.gz")
sha256sums=('$src')

prepare() {
    cd "\$pkgname-\$pkgver"
    export RUSTUP_TOOLCHAIN=stable
    cargo fetch --locked --target "\$(rustc --print host-tuple)"
}

build() {
    cd "\$pkgname-\$pkgver"
    export RUSTUP_TOOLCHAIN=stable
    export CARGO_TARGET_DIR=target
    cargo build --frozen --release
}

package() {
    cd "\$pkgname-\$pkgver"
    install -Dm755 target/release/rmx "\$pkgdir/usr/bin/rmx"
    install -Dm644 LICENSE "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
EOF

cat > "$out/rmx/.SRCINFO" <<EOF
pkgbase = rmx
	pkgdesc = $DESC
	pkgver = $version
	pkgrel = 1
	url = $REPO_URL
	arch = x86_64
	arch = aarch64
	license = MIT
	makedepends = cargo
	depends = glibc
	depends = libgcc
	conflicts = rmx-bin
	conflicts = rmx-fast-bin
	options = !debug
	source = rmx-$version.tar.gz::$REPO_URL/archive/refs/tags/v$version.tar.gz
	sha256sums = $src

pkgname = rmx
EOF

# ------------------------------------------------------- rmx-fast-bin (binary)
mkdir -p "$out/rmx-fast-bin"
cat > "$out/rmx-fast-bin/PKGBUILD" <<EOF
$MAINTAINER
# Generated by scripts/update-aur.sh; edit the script, not this file.
pkgname=rmx-fast-bin
_name=rmx
pkgver=$version
pkgrel=1
pkgdesc="$DESC (prebuilt static binary)"
arch=('x86_64' 'aarch64')
url="$REPO_URL"
license=('MIT')
provides=('rmx')
conflicts=('rmx' 'rmx-bin')
options=('!strip' '!debug')
source=("\$_name-\$pkgver-LICENSE::\$url/raw/v\$pkgver/LICENSE")
source_x86_64=("\$_name-\$pkgver-x86_64.tar.gz::\$url/releases/download/v\$pkgver/rmx-x86_64-unknown-linux-musl.tar.gz")
source_aarch64=("\$_name-\$pkgver-aarch64.tar.gz::\$url/releases/download/v\$pkgver/rmx-aarch64-unknown-linux-musl.tar.gz")
sha256sums=('$lic')
sha256sums_x86_64=('$x86')
sha256sums_aarch64=('$arm')

package() {
    install -Dm755 "\$srcdir/rmx" "\$pkgdir/usr/bin/rmx"
    install -Dm644 "\$srcdir/\$_name-\$pkgver-LICENSE" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
EOF

cat > "$out/rmx-fast-bin/.SRCINFO" <<EOF
pkgbase = rmx-fast-bin
	pkgdesc = $DESC (prebuilt static binary)
	pkgver = $version
	pkgrel = 1
	url = $REPO_URL
	arch = x86_64
	arch = aarch64
	license = MIT
	provides = rmx
	conflicts = rmx
	conflicts = rmx-bin
	options = !strip
	options = !debug
	source = rmx-$version-LICENSE::$REPO_URL/raw/v$version/LICENSE
	sha256sums = $lic
	source_x86_64 = rmx-$version-x86_64.tar.gz::$REPO_URL/releases/download/v$version/rmx-x86_64-unknown-linux-musl.tar.gz
	sha256sums_x86_64 = $x86
	source_aarch64 = rmx-$version-aarch64.tar.gz::$REPO_URL/releases/download/v$version/rmx-aarch64-unknown-linux-musl.tar.gz
	sha256sums_aarch64 = $arm

pkgname = rmx-fast-bin
EOF

echo "wrote $out/rmx and $out/rmx-fast-bin for $version"
