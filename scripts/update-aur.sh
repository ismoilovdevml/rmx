#!/usr/bin/env bash
# Generate packaging/aur/PKGBUILD and packaging/aur/.SRCINFO for a release.
#
# Usage: scripts/update-aur.sh <version> <SHA256SUMS.txt> [out_dir]
# Run from the repository root at the release tag (LICENSE is hashed).
#   version  e.g. 0.9.0 (no leading v)
#
# The package installs the static musl binaries from the GitHub release, so it
# needs no Rust toolchain on the user's machine. The AUR name `rmx-bin` belongs
# to an unrelated project that also installs /usr/bin/rmx, hence the distinct
# package name and the conflicts entry.
set -euo pipefail

PKGNAME="${AUR_PKGNAME:-rmx-fast-bin}"
REPO_URL="https://github.com/ismoilovdevml/rmx"

version="${1:?version required, e.g. 0.9.0}"
sums="${2:?path to SHA256SUMS.txt required}"
out="${3:-packaging/aur}"

if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "invalid version: $version" >&2
    exit 1
fi

sum_for() {
    local asset="$1" line
    line=$(grep -E "^[0-9a-f]{64}  ${asset}\$" "$sums" || true)
    if [ -z "$line" ]; then
        echo "no checksum for $asset in $sums" >&2
        exit 1
    fi
    printf '%s' "${line%% *}"
}

if command -v sha256sum >/dev/null; then
    lic=$(sha256sum LICENSE | cut -d' ' -f1)
else
    lic=$(shasum -a 256 LICENSE | cut -d' ' -f1)
fi
x86=$(sum_for rmx-x86_64-unknown-linux-musl.tar.gz)
arm=$(sum_for rmx-aarch64-unknown-linux-musl.tar.gz)

mkdir -p "$out"

cat > "$out/PKGBUILD" <<EOF
# Maintainer: Otabek Ismoilov <ismoilovdev at gmail dot com>
# Generated by scripts/update-aur.sh from the release's SHA256SUMS.txt.
pkgname=$PKGNAME
_name=rmx
pkgver=$version
pkgrel=1
pkgdesc="A faster rm written in Rust: parallel unlink, rm-compatible flags, never follows symlinks"
arch=('x86_64' 'aarch64')
url="$REPO_URL"
license=('MIT')
provides=('rmx')
conflicts=('rmx' 'rmx-bin')
options=('!strip' '!debug')
source=("\$_name-\$pkgver-LICENSE::\$url/raw/v\$pkgver/LICENSE")
source_x86_64=("\$_name-\$pkgver-x86_64.tar.gz::\$url/releases/download/v\$pkgver/rmx-x86_64-unknown-linux-musl.tar.gz")
source_aarch64=("\$_name-\$pkgver-aarch64.tar.gz::\$url/releases/download/v\$pkgver/rmx-aarch64-unknown-linux-musl.tar.gz")
sha256sums=('$lic')
sha256sums_x86_64=('$x86')
sha256sums_aarch64=('$arm')

package() {
    install -Dm755 "\$srcdir/rmx" "\$pkgdir/usr/bin/rmx"
    install -Dm644 "\$srcdir/\$_name-\$pkgver-LICENSE" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
}
EOF

cat > "$out/.SRCINFO" <<EOF
pkgbase = $PKGNAME
	pkgdesc = A faster rm written in Rust: parallel unlink, rm-compatible flags, never follows symlinks
	pkgver = $version
	pkgrel = 1
	url = $REPO_URL
	arch = x86_64
	arch = aarch64
	license = MIT
	provides = rmx
	conflicts = rmx
	conflicts = rmx-bin
	options = !strip
	options = !debug
	source = rmx-$version-LICENSE::$REPO_URL/raw/v$version/LICENSE
	sha256sums = $lic
	source_x86_64 = rmx-$version-x86_64.tar.gz::$REPO_URL/releases/download/v$version/rmx-x86_64-unknown-linux-musl.tar.gz
	sha256sums_x86_64 = $x86
	source_aarch64 = rmx-$version-aarch64.tar.gz::$REPO_URL/releases/download/v$version/rmx-aarch64-unknown-linux-musl.tar.gz
	sha256sums_aarch64 = $arm

pkgname = $PKGNAME
EOF

echo "wrote $out/PKGBUILD and $out/.SRCINFO for $PKGNAME $version"
